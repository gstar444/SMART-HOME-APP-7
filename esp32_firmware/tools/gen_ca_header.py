#!/usr/bin/env python3
"""Generate esp32_smart_home/ca_roots.h from the PEM files in ../certs/.

Each root is checked against a pinned SHA-256 fingerprint of its DER encoding
before it is embedded, so a corrupted or swapped PEM file fails loudly.
Fingerprints are the values published by the CAs:
  ISRG Root X1             96:BC:EC:06:26:49:76:F3:74:60:77:9A:CF:28:C5:A7:CF:E8:A3:C0:AA:E1:1A:8F:FC:EE:05:C0:BD:DF:08:C6
  DigiCert Global Root G2  CB:3C:CB:B7:60:31:E5:E0:13:8F:8D:D3:9A:23:F9:DE:47:FF:C3:5E:43:C1:14:4C:EA:27:D4:6A:5A:B1:CB:5F
Usage:  python3 tools/gen_ca_header.py
"""
import base64, hashlib, pathlib, re, sys

HERE = pathlib.Path(__file__).resolve().parent
ROOTS = [
    # (symbol, file, pinned sha256 of DER, comment)
    ("ROOT_CA_ISRG_X1", "isrg_root_x1.pem",
     "96bcec06264976f37460779acf28c5a7cfe8a3c0aae11a8ffcee05c0bddf08c6",
     "ISRG Root X1 (Let's Encrypt) - HiveMQ Cloud"),
    ("ROOT_CA_DIGICERT_G2", "digicert_global_root_g2.pem",
     "cb3ccbb76031e5e0138f8dd39a23f9de47ffc35e43c1144cea27d46a5ab1cb5f",
     "DigiCert Global Root G2 - EMQX public broker / EMQX Cloud (verify against the CA on your deployment page)"),
]

out = ["// GENERATED by tools/gen_ca_header.py - do not edit by hand.",
       "// Public root certificates only (no secrets). Re-run the generator to change them.",
       "#pragma once", ""]
for sym, fname, pin, comment in ROOTS:
    pem = (HERE.parent / "certs" / fname).read_text()
    m = re.search(r"-----BEGIN CERTIFICATE-----(.*?)-----END CERTIFICATE-----", pem, re.S)
    if not m:
        sys.exit(f"{fname}: no certificate found")
    der = base64.b64decode("".join(m.group(1).split()))
    got = hashlib.sha256(der).hexdigest()
    if got != pin:
        sys.exit(f"{fname}: fingerprint mismatch\n  expected {pin}\n  got      {got}")
    lines = [l for l in pem.strip().splitlines()]
    out.append(f"// {comment}")
    out.append(f"// SHA-256 fingerprint: {got}")
    out.append(f"static const char {sym}[] =")
    for i, l in enumerate(lines):
        out.append(f'    "{l}\\n"' + (";" if i == len(lines) - 1 else ""))
    out.append("")
dest = HERE.parent / "esp32_smart_home" / "ca_roots.h"
dest.write_text("\n".join(out))
print("wrote", dest, "-", len(ROOTS), "roots, fingerprints verified")
